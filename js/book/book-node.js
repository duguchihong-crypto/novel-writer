/* ======================================================
   基础元素
====================================================== */

const nodeTree =
    document.getElementById("tree");


/* ======================================================
   渲染全部节点
====================================================== */

function renderNodes() {

    if (
        !nodeTree ||
        !currentBook
    ) {
        return;
    }


    nodeTree.innerHTML = "";


    const nodes =
        Array.isArray(currentBook.nodes)
            ? currentBook.nodes
            : [];


    nodes.forEach(
        function (node) {

            createNodeElement(node);

        }
    );

}


/* ======================================================
   创建单个节点
====================================================== */

function createNodeElement(node) {

    if (!nodeTree || !node) {
        return null;
    }


    const element =
        document.createElement("div");


    /* ==================================================
       节点基础样式
    ================================================== */

    element.className =
        "node " +
        node.type;


    /* ==================================================
       节点 ID
    ================================================== */

    element.dataset.id =
        node.id;


    /* ==================================================
       节点名称
    ================================================== */

    element.textContent =
        node.title || "";


    /* ==================================================
       节点位置
    ================================================== */

    element.style.left =
        (
            typeof node.x === "number"
                ? node.x
                : 1500
        ) + "px";


    element.style.top =
        (
            typeof node.y === "number"
                ? node.y
                : 1650
        ) + "px";


    /* ==================================================
       以节点中心定位
    ================================================== */

    element.style.transform =
        "translate(-50%, -50%)";


    /* ==================================================
       加入树
    ================================================== */

    nodeTree.appendChild(
        element
    );


    return element;

}
