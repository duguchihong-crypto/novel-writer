/* ======================================================
   全书数据模块
====================================================== */


/* ======================================================
   读取全部书籍
====================================================== */

const books =
    JSON.parse(
        localStorage.getItem("novelBooks") || "[]"
    );


/* ======================================================
   读取当前书籍 ID
====================================================== */

const currentBookId =
    localStorage.getItem("currentBookId");


/* ======================================================
   获取当前书籍
====================================================== */

const currentBook =
    books.find(
        book =>
            String(book.id) ===
            String(currentBookId)
    );


/* ======================================================
   确保当前书籍拥有节点数组
====================================================== */

if (
    currentBook &&
    !Array.isArray(currentBook.nodes)
) {

    currentBook.nodes = [];

}
